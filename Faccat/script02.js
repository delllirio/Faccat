// Apostila 2007 — exercício 6: área do retângulo
// 6) Escreva um algoritmo para ler as dimensões de um retângulo (base e altura), calcular e escrever a área do retângulo. 

let base = Number(prompt("Digite a base do retângulo:"));
let altura = Number(prompt("Digite a altura do retângulo:"));
alert("Área: " + (base * altura));
